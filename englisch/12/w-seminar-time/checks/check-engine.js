/* W-Seminar "Time" – online check engine.
   Reads window.CHECK (generated by build_check.py) and renders into #check.
   Everything stays in this browser: no data is sent anywhere. Students save a
   result file; teachers can load result files below the check to re-score them.
   Client-side checks are not tamper-proof – use them only in supervised lessons. */
(function () {
    'use strict';
    var C = window.CHECK, root = document.getElementById('check');
    if (!C || !root) return;
    var KEY = 'check:' + C.id;

    function esc(s) { return String(s).replace(/[&<>"]/g, function (c) { return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]; }); }
    function hash() {
        var s = Array.prototype.join.call(arguments, '|');
        return crypto.subtle.digest('SHA-256', new TextEncoder().encode(s)).then(function (buf) {
            return Array.from(new Uint8Array(buf)).map(function (b) { return b.toString(16).padStart(2, '0'); }).join('').slice(0, 16);
        });
    }
    function rng(seed) {   // mulberry32
        return function () {
            seed |= 0; seed = seed + 0x6D2B79F5 | 0;
            var t = Math.imul(seed ^ seed >>> 15, 1 | seed);
            t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t;
            return ((t ^ t >>> 14) >>> 0) / 4294967296;
        };
    }
    function shuffle(arr, r) { arr = arr.slice(); for (var i = arr.length - 1; i > 0; i--) { var j = Math.floor(r() * (i + 1)); var t = arr[i]; arr[i] = arr[j]; arr[j] = t; } return arr; }
    function fmt(p) { return (Math.round(p * 2) / 2).toString().replace('.', ','); }
    function pad(n) { return String(n).padStart(2, '0'); }
    function when(ts) { var d = new Date(ts); return pad(d.getDate()) + '.' + pad(d.getMonth() + 1) + '.' + d.getFullYear() + ', ' + pad(d.getHours()) + ':' + pad(d.getMinutes()); }
    function np(percent) { for (var i = 0; i < C.scale.length; i++) if (percent >= C.scale[i][0]) return C.scale[i][1]; return 0; }

    var ITEMS = {};
    C.slots.forEach(function (s) { s.variants.forEach(function (v) { ITEMS[v.id] = v; }); });

    /* ---------------------------------------------------------------- state */
    var state = null;
    function load() { try { state = JSON.parse(localStorage.getItem(KEY) || 'null'); } catch (e) { state = null; } }
    function save() { try { localStorage.setItem(KEY, JSON.stringify(state)); } catch (e) { /* in-memory only */ } }
    function draw(seed) {
        var r = rng(seed), out = [];
        C.slots.forEach(function (s) {
            var v = s.variants[Math.floor(r() * s.variants.length)];
            var list = v.options || v.rows;
            out.push({ id: v.id, order: shuffle(list.map(function (o) { return o.id; }), r) });
        });
        return out;
    }

    /* ---------------------------------------------------------------- scoring */
    function scoreItem(it, ans) {
        if (it.type === 'single') {
            if (!ans) return Promise.resolve(0);
            return hash(C.salt, it.id, ans).then(function (x) { return x === it.key ? it.points : 0; });
        }
        if (it.type === 'multi') {
            ans = ans || [];
            return Promise.all(it.options.map(function (o) { return hash(C.salt, it.id, o.id, '1').then(function (x) { return x === o.h; }); }))
                .then(function (isTrue) {
                    var tp = 0, fp = 0, n = 0;
                    it.options.forEach(function (o, i) {
                        if (isTrue[i]) n++;
                        if (ans.indexOf(o.id) >= 0) { if (isTrue[i]) tp++; else fp++; }
                    });
                    return Math.round(Math.max(0, tp - fp) / n * it.points * 2) / 2;
                });
        }
        ans = ans || {};
        return Promise.all(it.rows.map(function (r) { return ans[r.id] ? hash(C.salt, it.id, r.id, ans[r.id]).then(function (x) { return x === r.h; }) : Promise.resolve(false); }))
            .then(function (ok) {
                var right = ok.filter(Boolean).length;
                return Math.round(right / it.rows.length * it.points * 2) / 2;
            });
    }
    function scoreAll(drawList, answers) {
        return Promise.all(drawList.map(function (d) { return scoreItem(ITEMS[d.id], answers[d.id]); })).then(function (pts) {
            var total = pts.reduce(function (a, b) { return a + b; }, 0);
            var percent = Math.round(total / C.max * 1000) / 10;
            return { perItem: pts, points: total, percent: percent, np: np(percent) };
        });
    }
    function code(s, res) { return hash(C.salt, s.name, res.points, s.submittedAt, JSON.stringify(s.answers)).then(function (x) { return x.slice(0, 6).toUpperCase(); }); }

    /* ---------------------------------------------------------------- screens */
    var tick = null;
    function render() {
        clearInterval(tick);
        load();
        if (!state) return renderStart();
        if (!state.submittedAt) return renderTest();
        return renderResult();
    }

    function teacherTools() {
        return '<details class="ck-teacher"><summary>For teachers: evaluate result files</summary>' +
            '<p class="ck-small">Select the result files your students saved (several at once). The page re-scores every file from its answers.</p>' +
            '<input type="file" id="ck-files" accept=".json,application/json" multiple>' +
            '<div id="ck-table"></div></details>';
    }
    function wireTeacher() {
        var inp = document.getElementById('ck-files');
        if (!inp) return;
        inp.addEventListener('change', function () {
            var files = Array.prototype.slice.call(inp.files);
            Promise.all(files.map(function (f) {
                return f.text().then(function (t) {
                    var r; try { r = JSON.parse(t); } catch (e) { return { file: f.name, err: 'not a result file' }; }
                    if (r.check !== C.id) return { file: f.name, err: 'belongs to another check' };
                    return scoreAll(r.draw, r.answers || {}).then(function (res) {
                        return code({ name: r.name, submittedAt: r.submittedAt, answers: r.answers || {} }, res).then(function (cd) {
                            return { file: f.name, r: r, res: res, ok: cd === r.code && res.points === r.points };
                        });
                    });
                });
            })).then(function (rows) {
                rows.sort(function (a, b) { return (a.r ? a.r.name : '').localeCompare(b.r ? b.r.name : ''); });
                var html = '<table class="ck-res"><tr><th>name</th><th>points</th><th>%</th><th>NP</th><th>handed in</th><th>file</th></tr>';
                var csv = 'name;points;max;percent;np;submitted;file check\n';
                rows.forEach(function (x) {
                    if (x.err) { html += '<tr><td colspan="6">' + esc(x.file) + ': ' + x.err + '</td></tr>'; return; }
                    html += '<tr><td>' + esc(x.r.name) + '</td><td>' + fmt(x.res.points) + ' / ' + C.max + '</td><td>' + String(x.res.percent).replace('.', ',') + '</td><td><b>' + x.res.np + '</b></td><td>' + when(x.r.submittedAt) + '</td><td>' + (x.ok ? '✓' : '<span class="ck-warn">changed?</span>') + '</td></tr>';
                    csv += [x.r.name, x.res.points, C.max, x.res.percent, x.res.np, when(x.r.submittedAt), x.ok ? 'ok' : 'check'].join(';') + '\n';
                });
                html += '</table><button class="ck-btn ck-ghost" id="ck-csv">Download table (.csv)</button>';
                var box = document.getElementById('ck-table'); box.innerHTML = html;
                document.getElementById('ck-csv').addEventListener('click', function () {
                    var a = document.createElement('a');
                    a.href = URL.createObjectURL(new Blob(['﻿' + csv], { type: 'text/csv;charset=utf-8' }));
                    a.download = C.id + '_results.csv'; document.body.appendChild(a); a.click(); a.remove();
                });
            });
        });
    }

    function renderStart() {
        root.innerHTML =
            '<div class="ck-card ck-start">' +
            '<p class="ck-kicker">' + esc(C.subtitle) + '</p><h1>' + esc(C.title) + '</h1>' +
            '<ul class="ck-facts"><li><b>' + C.minutes + '</b> minutes</li><li><b>' + C.max + '</b> points</li><li><b>' + C.slots.length + '</b> tasks</li></ul>' +
            '<p>Work on your own. You may not use other pages, notes or tools. Your answers are saved in this browser as you go; the timer keeps running if you reload. At the end, save your result file and keep the result on screen until your teacher has seen it.</p>' +
            (C.unitPage ? '<p class="ck-small">What the check covers: <a href="' + esc(C.unitPage) + '#check">can-do list</a>.</p>' : '') +
            '<label for="ck-name">First and last name</label><input id="ck-name" autocomplete="name">' +
            '<label for="ck-code">Start code from your teacher</label><input id="ck-code" autocomplete="off">' +
            '<p class="ck-err" id="ck-err" aria-live="polite"></p>' +
            '<button class="ck-btn" id="ck-go">Start the check</button></div>' + teacherTools();
        if (!window.crypto || !crypto.subtle) document.getElementById('ck-err').textContent = 'This page needs a secure connection (https). Please open it via edu-mrh.de.';
        document.getElementById('ck-go').addEventListener('click', function () {
            var name = document.getElementById('ck-name').value.trim(), cd = document.getElementById('ck-code').value.trim().toUpperCase();
            var err = document.getElementById('ck-err');
            if (name.split(/\s+/).length < 2) { err.textContent = 'Please enter your first and last name.'; return; }
            hash(C.salt, 'start', cd).then(function (x) {
                if (x !== C.start) { err.textContent = 'This start code is not correct.'; return; }
                var seed = Math.floor(Math.random() * 2147483647);
                state = { name: name, seed: seed, draw: draw(seed), answers: {}, startedAt: Date.now(), submittedAt: null };
                save(); render(); window.scrollTo(0, 0);
            });
        });
        wireTeacher();
    }

    function itemHTML(d, n) {
        var it = ITEMS[d.id], html = '<fieldset class="ck-item" data-id="' + it.id + '"><legend><span class="ck-n">' + n + '</span><span class="ck-pts">' + fmt(it.points) + ' P</span></legend><div class="ck-prompt">' + it.prompt + '</div>';
        var a = state.answers[it.id];
        if (it.type === 'single' || it.type === 'multi') {
            var byId = {}; it.options.forEach(function (o) { byId[o.id] = o; });
            if (it.type === 'multi') html += '<p class="ck-small">Select all that apply.</p>';
            html += '<div class="ck-opts">';
            d.order.forEach(function (oid) {
                var o = byId[oid], checked = it.type === 'single' ? a === oid : (a || []).indexOf(oid) >= 0;
                html += '<label class="ck-opt"><input type="' + (it.type === 'single' ? 'radio' : 'checkbox') + '" name="q' + it.id + '" value="' + oid + '"' + (checked ? ' checked' : '') + '><span>' + o.text + '</span></label>';
            });
            html += '</div>';
        } else {
            var rows = {}; it.rows.forEach(function (r) { rows[r.id] = r; });
            html += '<div class="ck-match">';
            d.order.forEach(function (rid) {
                var r = rows[rid], val = (a || {})[rid] || '';
                html += '<div class="ck-row"><span>' + r.text + '</span><select data-row="' + rid + '" aria-label="answer"><option value="">– choose –</option>' +
                    it.categories.map(function (c) { return '<option value="' + c.id + '"' + (val === c.id ? ' selected' : '') + '>' + esc(c.label) + '</option>'; }).join('') + '</select></div>';
            });
            html += '</div>';
        }
        return html + '</fieldset>';
    }
    function answered(d) {
        var a = state.answers[d.id], it = ITEMS[d.id];
        if (it.type === 'single') return !!a;
        if (it.type === 'multi') return a && a.length > 0;
        return a && Object.keys(a).filter(function (k) { return a[k]; }).length === it.rows.length;
    }
    function renderTest() {
        var html = '<div class="ck-bar" role="status"><span class="ck-who">' + esc(state.name) + '</span><span id="ck-prog"></span><span class="ck-time" id="ck-time"></span></div>';
        html += '<div class="ck-card"><p class="ck-kicker">' + esc(C.subtitle) + '</p><h1>' + esc(C.title) + '</h1></div>';
        state.draw.forEach(function (d, i) { html += itemHTML(d, i + 1); });
        html += '<div class="ck-card ck-end"><p id="ck-left"></p><button class="ck-btn" id="ck-submit">Hand in</button></div>';
        root.innerHTML = html;
        root.querySelectorAll('.ck-item').forEach(function (fs) {
            var id = fs.dataset.id, it = ITEMS[id];
            fs.addEventListener('change', function () {
                if (it.type === 'single') { var c = fs.querySelector('input:checked'); state.answers[id] = c ? c.value : null; }
                else if (it.type === 'multi') { state.answers[id] = Array.prototype.map.call(fs.querySelectorAll('input:checked'), function (x) { return x.value; }); }
                else { var m = {}; fs.querySelectorAll('select').forEach(function (s) { if (s.value) m[s.dataset.row] = s.value; }); state.answers[id] = m; }
                save(); progress();
            });
        });
        document.getElementById('ck-submit').addEventListener('click', function () {
            var open = state.draw.filter(function (d) { return !answered(d); }).length;
            if (!confirm(open ? open + ' task(s) are not complete. Hand in anyway?' : 'Hand in now? You cannot change your answers afterwards.')) return;
            submit();
        });
        progress(); clock(); tick = setInterval(clock, 1000);
    }
    function progress() {
        var done = state.draw.filter(answered).length;
        document.getElementById('ck-prog').textContent = done + ' / ' + state.draw.length + ' answered';
        var left = document.getElementById('ck-left');
        if (left) left.textContent = done === state.draw.length ? 'All tasks answered. Check your answers, then hand in.' : (state.draw.length - done) + ' task(s) still open.';
    }
    function clock() {
        var rest = Math.round(C.minutes * 60 - (Date.now() - state.startedAt) / 1000);
        var el = document.getElementById('ck-time'); if (!el) return;
        if (rest <= 0) { el.textContent = '0:00'; submit(); return; }
        el.textContent = Math.floor(rest / 60) + ':' + pad(rest % 60);
        el.classList.toggle('ck-low', rest <= 120);
    }
    function submit() {
        clearInterval(tick);
        if (state.submittedAt) return;
        state.submittedAt = Date.now();
        save(); render(); window.scrollTo(0, 0);
    }

    function renderResult() {
        root.innerHTML = '<div class="ck-card"><p>Scoring …</p></div>';
        scoreAll(state.draw, state.answers).then(function (res) {
            return code(state, res).then(function (cd) {
                state.result = { points: res.points, percent: res.percent, np: res.np, code: cd }; save();
                var mins = Math.round((state.submittedAt - state.startedAt) / 60000);
                var html = '<div class="ck-card ck-result">' +
                    '<p class="ck-kicker">' + esc(C.title) + '</p><h1>' + esc(state.name) + '</h1>' +
                    '<div class="ck-score"><div><span>' + fmt(res.points) + '</span> / ' + C.max + ' points</div><div><span>' + res.np + '</span> NP</div><div><span>' + String(res.percent).replace('.', ',') + '</span> %</div></div>' +
                    '<p class="ck-small">Handed in ' + when(state.submittedAt) + ' after ' + mins + ' min · check code <b class="ck-code">' + cd + '</b></p>' +
                    '<div class="ck-per">' + res.perItem.map(function (p, i) { var it = ITEMS[state.draw[i].id]; return '<span title="task ' + (i + 1) + '">' + (i + 1) + ': ' + fmt(p) + '/' + fmt(it.points) + '</span>'; }).join('') + '</div>' +
                    '<button class="ck-btn" id="ck-save">Save result file</button>' +
                    '<p class="ck-small">Keep this screen open until your teacher has seen it. Hand in the result file as your teacher tells you (e.g. Teams).</p>' +
                    '<details class="ck-reset"><summary>New attempt (teacher)</summary><input id="ck-rcode" placeholder="start code" autocomplete="off"><button class="ck-btn ck-ghost" id="ck-reset">Reset this browser</button></details></div>' +
                    teacherTools();
                root.innerHTML = html;
                document.getElementById('ck-save').addEventListener('click', function () {
                    var file = { check: C.id, title: C.title, name: state.name, startedAt: state.startedAt, submittedAt: state.submittedAt, seed: state.seed, draw: state.draw, answers: state.answers, points: res.points, max: C.max, percent: res.percent, np: res.np, code: cd };
                    var a = document.createElement('a');
                    a.href = URL.createObjectURL(new Blob([JSON.stringify(file, null, 1)], { type: 'application/json' }));
                    a.download = C.id + '_' + state.name.replace(/[^\wäöüÄÖÜß-]+/g, '-') + '.json';
                    document.body.appendChild(a); a.click(); a.remove();
                });
                document.getElementById('ck-reset').addEventListener('click', function () {
                    hash(C.salt, 'start', document.getElementById('ck-rcode').value.trim().toUpperCase()).then(function (x) {
                        if (x !== C.start) { alert('Wrong code.'); return; }
                        try { localStorage.removeItem(KEY); } catch (e) { }
                        state = null; render();
                    });
                });
                wireTeacher();
            });
        });
    }

    render();
})();
